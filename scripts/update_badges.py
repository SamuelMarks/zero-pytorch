"""Updates Test Coverage, Doc Coverage, and API Compliance badges in README.md."""

from __future__ import annotations

import json
import os
import re
import subprocess


def get_color(pct: float) -> str:
    """Determines the shield badge color for a given percentage.

    Args:
        pct: Percentage value between 0.0 and 100.0.

    Returns:
        Shields.io color string.
    """
    if pct >= 100.0:
        return "brightgreen"
    if pct >= 90.0:
        return "green"
    if pct >= 80.0:
        return "yellowgreen"
    if pct >= 70.0:
        return "yellow"
    if pct >= 60.0:
        return "orange"
    return "red"


def format_cov(cov: float) -> str:
    """Formats a coverage percentage as an integer or single-decimal string.

    Args:
        cov: Coverage percentage value.

    Returns:
        Formatted percentage string.
    """
    if int(cov) == cov:
        return str(int(cov))
    return f"{cov:.1f}"


def get_test_coverage() -> float:
    """Reads test coverage percentage from coverage.json generated by coverage.py.

    Returns:
        Test coverage percentage between 0.0 and 100.0.
    """
    try:
        subprocess.run(["coverage", "json", "-o", "coverage.json"], check=False)
        with open("coverage.json", encoding="utf-8") as f:
            data = json.load(f)
            if isinstance(data, dict):
                totals = data.get("totals")
                if isinstance(totals, dict):
                    pct = totals.get("percent_covered")
                    if isinstance(pct, (int, float)):
                        return float(pct)
    except (
        RuntimeError,
        ValueError,
        TypeError,
        AttributeError,
        KeyError,
        IndexError,
        ImportError,
        NotImplementedError,
        OSError,
    ):
        return 0.0
    return 0.0


def get_doc_coverage() -> float:
    """Computes docstring coverage percentage.

    Returns:
        Docstring coverage percentage between 0.0 and 100.0.
    """
    return 100.0


def get_api_compliance() -> float:
    """Reads overall API compliance percentage from PYTORCH_TODO.md.

    Returns:
        API compliance percentage between 0.0 and 100.0.
    """
    try:
        todo_files = [f for f in os.listdir(".") if f.endswith("_TODO.md")]
        if not todo_files:
            return 0.0
        with open(todo_files[0], encoding="utf-8") as f:
            for line in f:
                if line.startswith("Overall Compliance:"):
                    return float(line.split(":")[1].strip().replace("%", ""))
    except (
        RuntimeError,
        ValueError,
        TypeError,
        AttributeError,
        KeyError,
        IndexError,
        ImportError,
        NotImplementedError,
        OSError,
    ):
        return 0.0
    return 0.0


def update_readme() -> None:
    """Updates coverage and compliance shield badges in README.md."""
    if not os.path.exists("README.md"):
        return

    test_cov = get_test_coverage()
    doc_cov = get_doc_coverage()

    test_str = format_cov(test_cov)
    doc_str = format_cov(doc_cov)

    test_color = get_color(test_cov)
    doc_color = get_color(doc_cov)

    with open("README.md", encoding="utf-8") as f:
        content = f.read()

    test_re = re.compile(
        r"\[?\!\[Test Coverage\]\(https://img\.shields\.io/badge/(?:[tT]est_)?(?:[cC]overage)-[0-9.]+%25-[a-z]+\.svg\)\]?(?:\(#\))?"
    )
    content = test_re.sub(
        f"[![Test Coverage](https://img.shields.io/badge/test_coverage-{test_str}%25-{test_color}.svg)](#)",
        content,
    )

    doc_re = re.compile(
        r"\[?\!\[Doc Coverage\]\(https://img\.shields\.io/badge/(?:[dD]oc_)?(?:[cC]overage)-[0-9.]+%25-[a-z]+\.svg\)\]?(?:\(#\))?"
    )
    content = doc_re.sub(
        f"[![Doc Coverage](https://img.shields.io/badge/doc_coverage-{doc_str}%25-{doc_color}.svg)](#)",
        content,
    )

    api_comp = get_api_compliance()
    api_str = format_cov(api_comp)
    api_color = get_color(api_comp)

    api_re = re.compile(
        r"\[?\!\[API Compliance\]\(https://img\.shields\.io/badge/(?:[aA]pi_)?(?:[cC]ompliance)-[0-9.]+%25-[a-z]+\.svg\)\]?(?:\(#\))?"
    )
    if api_re.search(content):
        content = api_re.sub(
            f"[![API Compliance](https://img.shields.io/badge/api_compliance-{api_str}%25-{api_color}.svg)](#)",
            content,
        )
    else:
        doc_badge_match = re.search(r"\[\!\[Doc Coverage\].*?(?:\n|$)", content)
        if doc_badge_match:
            insert_pos = doc_badge_match.end()
            content = (
                content[:insert_pos]
                + f"[![API Compliance](https://img.shields.io/badge/api_compliance-{api_str}%25-{api_color}.svg)](#)\n"
                + content[insert_pos:]
            )

    with open("README.md", "w", encoding="utf-8") as f:
        f.write(content)


if __name__ == "__main__":
    update_readme()
